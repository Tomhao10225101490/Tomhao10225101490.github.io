def escape(value: str) -> str:
    return html.escape(value, quote=True)


def add_locale_attrs(content: str) -> str:
    missing = []

    def repl(match: re.Match[str]) -> str:
        zh = match.group(1)
        en = match.group(2)
        if zh not in TRANSLATIONS:
            missing.append(zh)
            return match.group(0)
        ja, ko = TRANSLATIONS[zh]
        return (
            f'data-zh="{escape(zh)}" data-en="{escape(en)}" '
            f'data-ja="{escape(ja)}" data-ko="{escape(ko)}"'
        )

    updated = re.sub(
        r'data-zh="([^"]*)" data-en="([^"]*)"',
        repl,
        content,
    )

    if missing:
        raise SystemExit(f"Missing translations for: {missing}")

    return updated


